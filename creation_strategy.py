def shot_direction(position: int, count: int) -> str:
    """A slot has an editorial purpose; the planner still chooses its actual scene."""
    if position == 0:
        purpose = "封面：选与标题同一吸引点的瞬间或可见反差，主体清楚；不是默认正中摆拍。"
    elif position == 1:
        purpose = "信息展开：呈现正文最关键的可见细节，采用与封面不同的景别；没有该细节依据就改拍已知使用场景。"
    elif position == count - 1:
        purpose = "收尾：回应正文的一个选择顾虑或展示与环境的关系，不重复封面。"
    else:
        purpose = "补充证据：选择尚未展示的已知细节或使用关系，与相邻图改变景别和信息点，不臆造隐藏结构。"
    return f"当前仅生成第{position + 1}/{count}张独立图片。{purpose}最终以本张规划为准，整组方案只用于保持连续性。"
